/*
GLSL của cảnh hoa anh đào.
Toàn bộ chuyển động và hình dạng cánh hoa được tính trên GPU:
- Đỉnh: mỗi cánh hoa là một quad; vị trí, độ rơi, độ xoay, độ lật tính từ seed + thời gian.
- Mảnh: cánh hoa vẽ bằng hàm khoảng cách có dấu (SDF), không cần texture.
Độ nhoè mô phỏng xoá phông bằng cách nới rộng viền SDF theo khoảng cách tới mặt phẳng nét.
*/
(function (window) {
	"use strict";

	var vertex = [
		"attribute vec2 aCorner;",
		"attribute vec4 aSeed;",
		"attribute vec4 aRand;",
		"",
		"uniform mat4 uViewProjection;",
		"uniform float uTime;",
		"uniform float uAspect;",
		"uniform float uTanHalfFov;",
		"uniform float uCameraZ;",
		"uniform vec2 uDepthRange;",
		"uniform vec2 uFallRange;",
		"uniform float uDrift;",
		"uniform float uSwayAmplitude;",
		"uniform float uSwayFrequency;",
		"uniform vec2 uSpinRange;",
		"uniform vec2 uSizeRange;",
		"uniform float uFocus;",
		"uniform float uDofRange;",
		"uniform float uSoftNear;",
		"uniform float uSoftFar;",
		"uniform float uAlphaNear;",
		"uniform float uAlphaFar;",
		"uniform float uScaleFar;",
		"",
		"varying vec2 vUv;",
		"varying float vSoft;",
		"varying float vAlpha;",
		"varying float vTint;",
		"",
		"void main() {",
		"  float t = uTime;",
		"",
		"  float z = mix(uDepthRange.x, uDepthRange.y, aSeed.z);",
		"  float depth = max(uCameraZ - z, 0.001);",
		"",
		"  // Nửa chiều cao khung hình tại độ sâu này, để cánh hoa phủ kín mọi cỡ màn hình.",
		"  float halfHeight = uTanHalfFov * depth;",
		"  float halfWidth = halfHeight * uAspect;",
		"",
		"  float fallSpeed = mix(uFallRange.x, uFallRange.y, aRand.x);",
		"  float y01 = fract(0.5 + aSeed.y * 0.5 - fallSpeed * t / (2.0 * halfHeight));",
		"  float x01 = fract(0.5 + aSeed.x * 0.5 + uDrift * t / (2.0 * halfWidth));",
		"",
		"  float sway = sin(t * uSwayFrequency + aRand.w * 6.2831 + z * 0.07);",
		"  x01 = fract(x01 + sway * uSwayAmplitude / (2.0 * halfWidth));",
		"",
		"  vec3 position;",
		"  position.x = (x01 * 2.0 - 1.0) * halfWidth;",
		"  position.y = (y01 * 2.0 - 1.0) * halfHeight;",
		"  position.z = z;",
		"",
		"  // Độ nhoè: 0 là đúng mặt phẳng nét, 1 là xa nhất.",
		"  float dof = clamp(abs(depth - uFocus) / uDofRange, 0.0, 1.0);",
		"",
		"  float size = mix(uSizeRange.x, uSizeRange.y, aRand.z);",
		"  size *= pow(depth / uFocus, 0.55);",
		"  size *= mix(1.0, uScaleFar, dof);",
		"",
		"  float spin = mix(uSpinRange.x, uSpinRange.y, aSeed.w);",
		"  float angle = t * spin + aRand.w * 6.2831;",
		"  float tumble = t * spin * 2.1 + aRand.w * 9.421;",
		"  float squash = 0.45 + 0.55 * abs(cos(tumble));",
		"",
		"  vec2 corner = aCorner * size;",
		"  corner.x *= squash;",
		"",
		"  float c = cos(angle);",
		"  float s = sin(angle);",
		"  position.xy += vec2(corner.x * c - corner.y * s, corner.x * s + corner.y * c);",
		"",
		"  vUv = aCorner;",
		"  vSoft = mix(uSoftNear, uSoftFar, dof);",
		"  vTint = fract(aRand.z * 7.31 + aSeed.w * 3.17);",
		"  vAlpha = mix(uAlphaNear, uAlphaFar, dof) * (0.84 + 0.16 * vTint);",
		"",
		"  gl_Position = uViewProjection * vec4(position, 1.0);",
		"}",
	].join("\n");

	var fragment = [
		"precision mediump float;",
		"",
		"varying vec2 vUv;",
		"varying float vSoft;",
		"varying float vAlpha;",
		"varying float vTint;",
		"",
		"uniform vec3 uColorLight;",
		"uniform vec3 uColorPink;",
		"uniform vec3 uColorDeep;",
		"",
		"// Cánh hoa anh đào: hẹp ngang, loe ở đầu, khía một rãnh nhỏ và thuôn về cuống.",
		"float petalDistance(vec2 p) {",
		"  p.x *= 1.46;",
		"  float d = length(p - vec2(0.0, -0.06)) - 0.99;",
		"  d += max(0.0, -p.y - 0.3) * 0.92;",
		"  float notch = length(p - vec2(0.0, 1.05)) - 0.37;",
		"  return max(d, -notch);",
		"}",
		"",
		"void main() {",
		"  float d = petalDistance(vUv);",
		"  float soft = max(vSoft, 0.016);",
		"  float alpha = smoothstep(soft, -soft * 0.45, d);",
		"",
		"  if (alpha < 0.004) {",
		"    discard;",
		"  }",
		"",
		"  float inside = clamp(-d, 0.0, 1.0);",
		"  vec3 color = mix(uColorPink, uColorLight, pow(inside, 1.6) * 0.75);",
		"  color = mix(color, uColorDeep, vTint * 0.26 * (1.0 - inside));",
		"",
		"  gl_FragColor = vec4(color, alpha * vAlpha);",
		"}",
	].join("\n");

	window.SakuraShaders = {
		vertex: vertex,
		fragment: fragment,
	};
})(window);
