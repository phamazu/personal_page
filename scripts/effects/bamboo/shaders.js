/*
GLSL của cảnh lá trúc.
Toàn bộ chuyển động và hình dạng lá được tính trên GPU:
- Đỉnh: mỗi lá là một quad hẹp; vị trí, độ rơi, đung đưa, xoay, lật tính từ seed + thời gian.
- Mảnh: phiến lá vẽ bằng hàm khoảng cách có dấu (SDF), có gân giữa và độ cong riêng,
  hoàn toàn không cần texture.
Độ nhoè mô phỏng xoá phông bằng cách nới rộng viền SDF theo khoảng cách tới mặt phẳng nét.
*/
(function (window) {
	"use strict";

	var vertex = [
		"attribute vec2 aCorner;",
		"attribute vec4 aSeed;",
		"attribute vec4 aRand;",
		"",
		"uniform mat4 uViewProjection;",
		"uniform float uTime;",
		"uniform float uAspect;",
		"uniform float uTanHalfFov;",
		"uniform float uCameraZ;",
		"uniform vec2 uDepthRange;",
		"uniform vec2 uFallRange;",
		"uniform float uDrift;",
		"uniform float uSwayAmplitude;",
		"uniform float uSwayFrequency;",
		"uniform vec2 uSpinRange;",
		"uniform vec2 uSizeRange;",
		"uniform float uLeafAspect;",
		"uniform float uFocus;",
		"uniform float uDofRange;",
		"uniform float uSoftNear;",
		"uniform float uSoftFar;",
		"uniform float uAlphaNear;",
		"uniform float uAlphaFar;",
		"uniform float uScaleFar;",
		"uniform float uPixelHeight;",
		"",
		"varying vec2 vUv;",
		"varying float vSoft;",
		"varying float vAlpha;",
		"varying float vTint;",
		"varying float vEdge;",
		"",
		"void main() {",
		"  float t = uTime;",
		"",
		"  float z = mix(uDepthRange.x, uDepthRange.y, aSeed.z);",
		"  float depth = max(uCameraZ - z, 0.001);",
		"",
		"  // Nửa chiều cao khung hình tại độ sâu này, để lá phủ kín mọi cỡ màn hình.",
		"  float halfHeight = uTanHalfFov * depth;",
		"  float halfWidth = halfHeight * uAspect;",
		"",
		"  float fallSpeed = mix(uFallRange.x, uFallRange.y, aRand.x);",
		"  float y01 = fract(0.5 + aSeed.y * 0.5 - fallSpeed * t / (2.0 * halfHeight));",
		"  float x01 = fract(0.5 + aSeed.x * 0.5 + uDrift * t / (2.0 * halfWidth));",
		"",
		"  // Đung đưa: lá trúc liệng qua lại rộng hơn cánh hoa.",
		"  float sway = sin(t * uSwayFrequency + aRand.w * 6.2831 + z * 0.07);",
		"  x01 = fract(x01 + sway * uSwayAmplitude / (2.0 * halfWidth));",
		"",
		"  vec3 position;",
		"  position.x = (x01 * 2.0 - 1.0) * halfWidth;",
		"  position.y = (y01 * 2.0 - 1.0) * halfHeight;",
		"  position.z = z;",
		"",
		"  // Độ nhoè: 0 là đúng mặt phẳng nét, 1 là xa nhất.",
		"  float dof = clamp(abs(depth - uFocus) / uDofRange, 0.0, 1.0);",
		"",
		"  float size = mix(uSizeRange.x, uSizeRange.y, aRand.z);",
		"  size *= pow(depth / uFocus, 0.55);",
		"  size *= mix(1.0, uScaleFar, dof);",
		"  // Màn hình hẹp có khung nhìn hẹp hơn: thu nhỏ lá để tỉ lệ vẫn cân.",
		"  size *= clamp(pow(clamp(uAspect / 1.6, 0.3, 1.0), 0.55), 0.55, 1.0);",
		"",
		"  float spin = mix(uSpinRange.x, uSpinRange.y, aSeed.w);",
		"  float angle = t * spin + aRand.w * 6.2831;",
		"  float tumble = t * spin * 1.9 + aRand.w * 9.421;",
		"  float squash = 0.4 + 0.6 * abs(cos(tumble));",
		"",
		"  vec2 corner = aCorner * size;",
		"  // Ép hẹp trục x để quad vuông thành phiến lá dài.",
		"  corner.x *= squash * uLeafAspect;",
		"",
		"  float c = cos(angle);",
		"  float s = sin(angle);",
		"  position.xy += vec2(corner.x * c - corner.y * s, corner.x * s + corner.y * c);",
		"",
		"  vUv = aCorner;",
		"",
		"  // Số pixel ứng với một đơn vị UV: dùng để khử răng cưa vừa một pixel.",
		"  float pixelsPerWorld = (uPixelHeight * 0.5) / (uTanHalfFov * depth);",
		"  float pixelsPerUv = max(size * pixelsPerWorld, 0.0001);",
		"  vEdge = 1.35 / pixelsPerUv;",
		"",
		"  vSoft = mix(uSoftNear, uSoftFar, dof);",
		"  vTint = fract(aRand.z * 7.31 + aSeed.w * 3.17);",
		"  vAlpha = mix(uAlphaNear, uAlphaFar, dof) * (0.82 + 0.18 * vTint);",
		"",
		"  gl_Position = uViewProjection * vec4(position, 1.0);",
		"}",
	].join("\n");

	var fragment = [
		"precision mediump float;",
		"",
		"varying vec2 vUv;",
		"varying float vSoft;",
		"varying float vAlpha;",
		"varying float vTint;",
		"varying float vEdge;",
		"",
		"uniform vec3 uColorPale;",
		"uniform vec3 uColorLeaf;",
		"uniform vec3 uColorShade;",
		"",
		"/*",
		"  Phiến lá trúc: dài, hẹp, nhọn ở đầu, thuôn ở cuống.",
		"  Bề rộng nửa lá theo phương y, đỉnh ở khoảng một phần ba trên.",
		"*/",
		"float bladeWidth(float y) {",
		"  float up = max(0.0, 1.0 - y);",
		"  float down = max(0.0, 1.0 + y);",
		"  return 0.627 * pow(up, 0.7) * pow(down, 0.9);",
		"}",
		"",
		"float leafDistance(vec2 p) {",
		"  // Độ cong riêng của từng lá, mỗi lá cong một hướng khác nhau.",
		"  float bend = (vTint - 0.5) * 0.42;",
		"  p.x -= bend * (1.0 - p.y * p.y);",
		"  return abs(p.x) - bladeWidth(clamp(p.y, -1.0, 1.0));",
		"}",
		"",
		"void main() {",
		"  float d = leafDistance(vUv);",
		"  float soft = max(vSoft, vEdge);",
		"  float alpha = smoothstep(soft, -soft * 0.4, d);",
		"",
		"  if (alpha < 0.004) {",
		"    discard;",
		"  }",
		"",
		"  float inside = clamp(-d * 1.7, 0.0, 1.0);",
		"",
		"  // Phiến: xanh non ở giữa, đậm dần ra mép; một ít lá ngả vàng non.",
		"  vec3 color = mix(uColorLeaf, uColorPale, pow(inside, 1.5) * 0.5);",
		"  color = mix(color, uColorShade, vTint * 0.3 * (1.0 - inside));",
		"",
		"  // Gân giữa sáng hơn, chạy dọc theo chiều dài lá.",
		"  float rib = smoothstep(0.075, 0.0, abs(vUv.x - (vTint - 0.5) * 0.42 * (1.0 - vUv.y * vUv.y)));",
		"  color = mix(color, uColorPale, rib * 0.32);",
		"",
		"  gl_FragColor = vec4(color, alpha * vAlpha);",
		"}",
	].join("\n");

	window.BambooShaders = {
		vertex: vertex,
		fragment: fragment,
	};
})(window);
